"""
xiong_common.py

Shared utilities for the Xiong et al. (2025) baseline reimplementation
("Multimodal ultra-short-term probabilistic solar power forecasting with
generative AI and Transformer", Adv. Appl. Energy 20:100250).

Everything here is deliberately dependency-light so the three training stages
and the evaluation script agree on:

  * how frames are normalised  (uint8-safe -- do NOT repeat the uint8 wraparound bug)
  * how the target is parameterised (CSI or z-scored GHI) and inverted
  * how images are degraded during training so the frozen ResNet sees something
    close to what the conditional diffusion model will produce at test time
    (paper Sec. 2.3.3: "Gaussian noise and Gaussian blur are added to the
    original image to make it close to the predicted image generated by the CDM")

Dataset contract (data.sirta_dataset.SeqDataset_SIRTA,
attribute_list=["label","image","feature"]):

  image_x   [B, Tin,  3, H, W]   past frames, i-Tin+1 .. i
  image_y   [B, Tout, 3, H, W]   future frames, i+1 .. i+Tout
  label_x   [B, Tin,  1]         past GHI  (W/m^2)
  label_y   [B, Tout, 1]         future GHI (W/m^2)   <- ground truth
  feature_x [B, Tin,  4]         past covariates,  index 3 == Iclr
  feature_y [B, Tout, 4]         future covariates, index 3 == Iclr

NOTE ON feature COLUMNS: only column 3 (Iclr) is pinned down by the existing
code base. Columns 0..2 are treated as the deterministic temporal covariates
u_{1:T} of the paper. If that mapping is wrong for your dataset, change
TEMPORAL_IDX in the config rather than here.
"""

