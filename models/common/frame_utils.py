def build_xcfg(configs):
    """
    The SkyGPT repo's YAMLs are nested by concern (Training / ImageSequence /
    <Network>). The Xiong modules were written against a flat dict. Rather than
    thread `configs["Xiong"]["Network"][...]` through every module, translate
    once, here, so there is exactly one place that knows the mapping.

    Everything the modules read is present in the returned dict; anything the
    YAML omits falls back to the paper-default below.
    """
    X = configs.get("Xiong", {})
    net = X.get("Network", {})
    vid = X.get("Video", {})
    res = X.get("Resnet", {})
    mm = X.get("Multimodal", {})
    gp = X.get("GP", {})
    tgt = X.get("Target", {})
    seq = configs["ImageSequence"]

    def g(d, k, default):
        v = d.get(k, default)
        return default if v is None else v

    # This repo allows `random_seed: False` to mean "do not seed" (main.py
    # skips seeding on a falsy value). That is fine for training, but the
    # forecast() mixture draw needs a concrete integer, so coerce here.
    _seed = g(configs["Training"], "random_seed", 1)
    _seed = 1 if not _seed else int(_seed)

    return dict(
        seed=_seed,
        data=dict(
            image_size=seq["image_resize"],
            img_channels=g(seq, "image_channels", 3),
            seq_len=seq["seq_length"],
            pred_len=seq["pred_length"],
            # feature_x channels are [h, m, doy, iclr] in preprocessing_SIRTA_sequence
            temporal_idx=g(net, "temporal_idx", [0, 1, 2]),
            iclr_idx=g(net, "iclr_idx", 3),
        ),
        target=dict(
            mode=g(tgt, "mode", "csi"),
            csi_clip=g(tgt, "csi_clip", 1.67),
            csi_mean=g(tgt, "csi_mean", 0.7256),
            csi_std=g(tgt, "csi_std", 0.3822),
            iclr_floor=g(tgt, "iclr_floor", 1.0),
            ghi_mean=g(tgt, "ghi_mean", 0.0),
            ghi_std=g(tgt, "ghi_std", 1.0),
        ),
        video=dict(
            enc_base=g(vid, "enc_base", 32),
            motion_ch=g(vid, "motion_ch", 64),
            sde_hidden=g(vid, "sde_hidden", 128),
            sde_dt=g(vid, "sde_dt", 1.0),
            sde_noise_scale=g(vid, "sde_noise_scale", 1.0),
            sde_substeps=g(vid, "sde_substeps", 1),
            unet_base=g(vid, "unet_base", 64),
            unet_ch_mult=g(vid, "unet_ch_mult", [1, 2, 2]),
            emb_dim=g(vid, "emb_dim", 256),
            attn_res=g(vid, "attn_res", [16]),
            motion_spatial=g(vid, "motion_spatial", True),
            dropout=g(vid, "dropout", 0.0),
            num_train_timesteps=g(vid, "num_train_timesteps", 1000),
            beta_schedule=g(vid, "beta_schedule", "linear"),
            ddim_steps=g(vid, "ddim_steps", 50),
            ddim_eta=g(vid, "ddim_eta", 0.0),
        ),
        resnet=dict(
            base=g(res, "base", 64),
            layers=g(res, "layers", [2, 2, 2, 2]),
            feat_dim=g(res, "feat_dim", 512),
            spectral_c=g(res, "spectral_c", 6.0),
            use_spectral_norm=g(res, "use_spectral_norm", True),
            aug=dict(noise_std=g(res, "aug_noise_std", 0.05),
                     blur_sigma_max=g(res, "aug_blur_sigma_max", 0.8)),
        ),
        multimodal=dict(
            d_model=g(mm, "d_model", 128),
            n_heads=g(mm, "n_heads", 4),
            e_layers=g(mm, "e_layers", 2),
            d_layers=g(mm, "d_layers", 1),
            d_ff=g(mm, "d_ff", 256),
            dropout=g(mm, "dropout", 0.1),
            label_len=g(mm, "label_len", 4),
            spectral_c=g(mm, "spectral_c", 6.0),
            use_spectral_norm=g(mm, "use_spectral_norm", True),
        ),
        gp=dict(
            n_rff=g(gp, "n_rff", 1024),
            kernel_scale=g(gp, "kernel_scale", 2.0),
            ridge=g(gp, "ridge", 0.001),
            add_observation_noise=g(gp, "add_observation_noise", True),
        ),
    )


def build_target_transform(cfg) -> TargetTransform:
    t = cfg["target"]
    return TargetTransform(
        mode=t.get("mode", "csi"),
        csi_clip=t.get("csi_clip", 1.67),
        csi_mean=t.get("csi_mean", 0.7256),
        csi_std=t.get("csi_std", 0.3822),
        iclr_floor=t.get("iclr_floor", 1.0),
        ghi_mean=t.get("ghi_mean", 0.0),
        ghi_std=t.get("ghi_std", 1.0),
    )


# --------------------------------------------------------------------------- #
# batch unpacking (single place that knows the dataset's column layout)
# --------------------------------------------------------------------------- #
def unpack_batch(batch, cfg, device):
    """
    Returns a dict of tensors already on `device`, in model-ready units.

      x_frames [B,Tin, 3,H,W]  in [-1,1]
      y_frames [B,Tout,3,H,W]  in [-1,1]
      ghi_x    [B,Tin]         W/m^2
      ghi_y    [B,Tout]        W/m^2  (ground truth)
      iclr_x   [B,Tin]         W/m^2
      iclr_y   [B,Tout]        W/m^2
      u_x      [B,Tin, nu]     temporal covariates
      u_y      [B,Tout,nu]     temporal covariates
      z_x      [B,Tin]         normalised target, history
      z_y      [B,Tout]        normalised target, future
    """
    ti = cfg["data"]["temporal_idx"]
    ii = cfg["data"]["iclr_idx"]
    tt = build_target_transform(cfg)

    out = {}
    out["x_frames"] = normalize_frames(batch["image_x"]).to(device)
    if "image_y" in batch:
        out["y_frames"] = normalize_frames(batch["image_y"]).to(device)

    out["ghi_x"] = batch["label_x"][..., 0].float().to(device)
    out["ghi_y"] = batch["label_y"][..., 0].float().to(device)
    out["iclr_x"] = batch["feature_x"][..., ii].float().to(device)
    out["iclr_y"] = batch["feature_y"][..., ii].float().to(device)
    out["u_x"] = batch["feature_x"][..., ti].float().to(device)
    out["u_y"] = batch["feature_y"][..., ti].float().to(device)

    out["z_x"] = tt.encode(out["ghi_x"], out["iclr_x"])
    out["z_y"] = tt.encode(out["ghi_y"], out["iclr_y"])
    return out


# --------------------------------------------------------------------------- #
# soft spectral normalisation  (paper Eq. 22 -- SNGP's bounded variant)
# --------------------------------------------------------------------------- #
class SoftSpectralNorm(nn.Module):
    """
    Eq. (22):   A_l <- c * A_l / lambda_hat   if c < lambda_hat, else unchanged.

    This is *not* torch.nn.utils.spectral_norm, which always divides by the
    spectral norm. The bounded form keeps the mapping distance-preserving
    (bi-Lipschitz) without over-constraining layers that are already contractive
    -- which is the whole point of criterion 2 in Sec. 2.3.2.

    Implemented as a torch parametrization rather than a forward pre-hook. That
    matters: nn.MultiheadAttention reads `self.out_proj.weight` directly instead
    of calling the submodule, so a pre-hook on out_proj would never fire (and
    would silently detach the weight from the optimiser). A parametrization
    makes `.weight` a property, so it recomputes on every access.

    lambda_hat comes from one power iteration, updated only in training mode.
    """

    def __init__(self, weight, c=6.0, n_power_iterations=1, eps=1e-12):
        super().__init__()
        w_mat = weight.reshape(weight.shape[0], -1)
        self.register_buffer("_u", F.normalize(torch.randn(w_mat.shape[0]), dim=0))
        self.register_buffer("_v", F.normalize(torch.randn(w_mat.shape[1]), dim=0))
        self.c = float(c)
        self.n_power_iterations = int(n_power_iterations)
        self.eps = float(eps)

    def forward(self, w):
        w_mat = w.reshape(w.shape[0], -1)
        if self.training:
            with torch.no_grad():
                u, v = self._u, self._v
                for _ in range(self.n_power_iterations):
                    v = F.normalize(w_mat.t().detach() @ u, dim=0, eps=self.eps)
                    u = F.normalize(w_mat.detach() @ v, dim=0, eps=self.eps)
                self._u.copy_(u)
                self._v.copy_(v)
        sigma = torch.dot(self._u, w_mat @ self._v)
        factor = torch.where(sigma > self.c, self.c / (sigma + self.eps),
                             torch.ones_like(sigma))
        return w * factor


def soft_spectral_norm(module, name="weight", c=6.0, n_power_iterations=1):
    import torch.nn.utils.parametrize as P
    if P.is_parametrized(module, name):
        return module
    w = getattr(module, name)
    if w is None or w.dim() < 2:
        return module
    P.register_parametrization(module, name,
                               SoftSpectralNorm(w, c, n_power_iterations))
    return module


def apply_soft_sn(root: nn.Module, c=6.0,
                  types=(nn.Conv1d, nn.Conv2d, nn.Linear)):
    """
    Recursively apply Eq. (22) to every Conv/Linear weight in `root`, including
    the packed in_proj_weight of nn.MultiheadAttention (which is not a submodule
    and would otherwise be missed entirely).
    """
    for m in root.modules():
        if isinstance(m, nn.MultiheadAttention):
            if getattr(m, "in_proj_weight", None) is not None:
                soft_spectral_norm(m, name="in_proj_weight", c=c)
            continue                      # out_proj is picked up below
    for m in root.modules():
        if isinstance(m, types):
            soft_spectral_norm(m, name="weight", c=c)
    return root


